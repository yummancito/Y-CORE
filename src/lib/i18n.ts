// Y-Core i18n module (thin)
//
// Why this file is small:
//   Spanish (the default locale) stays bundled inline so first paint has
//   translations available synchronously — no flash of untranslated keys.
//   The other 6 locales are split by Vite into separate chunks via dynamic
//   import(). They only fetch when the user actually switches language,
//   cutting the initial JS parse cost dramatically (was 4054 lines, now ~).
//
// Public API (unchanged from the original module, so the 35+ component
// call sites keep working without edits):
//   - t(key)                       sync string lookup
//   - tf(key, params)              sync template interpolation
//   - detectSystemLanguage(locale) sync language detection
//   - setLanguage(lang)            now returns Promise<void> (resolves when
//                                  the locale chunk has been loaded and the
//                                  active dict has been swapped)
// New helpers:
//   - subscribe(cb) -> () => void  notified on every language change
//   - getLanguage()                reads currentLang without subscribing

