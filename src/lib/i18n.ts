// Lazy loaders for non-default languages. Vite emits one chunk per locale,
// fetched only when the user actively switches to that language.
const lazy: Partial<Record<Language, () => Promise<Dict>>> = {
  en: () => import('./locales/en').then((m) => m.default),
  fr: () => import('./locales/fr').then((m) => m.default),
  pt: () => import('./locales/pt').then((m) => m.default),
  de: () => import('./locales/de').then((m) => m.default),
  zh: () => import('./locales/zh').then((m) => m.default),
  hi: () => import('./locales/hi').then((m) => m.default),
}

let currentLang: Language = 'es'
let currentDict: Dict = es
const cache = new Map<Language, Dict>([['es', es]])
const listeners = new Set<(lang: Language) => void>()

// Eagerly load English in the background so it can serve as a universal
// fallback for fr/de/pt/zh/hi users when a key hasn't been translated to their
// language yet. Without this, t() would fall through to the raw key name
// whenever the user is in a non-English, non-Spanish locale and English
// hasn't been visited yet.
lazy.en!()
  .then((dict) => {
    cache.set('en', dict)
  })
  .catch(() => {
    // English fallback is best-effort; if it fails the key itself is shown
  })

export function detectSystemLanguage(locale: string): Language {
  const lang = locale.split('-')[0].toLowerCase() as Language
  if (lang === 'es' || lang in lazy) return lang
  return 'en'
}

export async function setLanguage(lang: string): Promise<void> {
  if (lang !== 'es' && !(lang in lazy)) return
  const target = lang as Language
  if (currentLang === target) return
  let dict = cache.get(target)
  if (!dict) {
    dict = await lazy[target]!()
    cache.set(target, dict)
  }
  currentDict = dict
  currentLang = target
  listeners.forEach((l) => l(target))
}

export function subscribe(cb: (lang: Language) => void): () => void {
  listeners.add(cb)
  return () => {
    listeners.delete(cb)
  }
}

export function getLanguage(): Language {
  return currentLang
}

export function t(key: string): string {
  // Lookup chain: current language → English fallback → Spanish (source of
  // truth) → raw key. Loading English eagerly above makes the second branch
  // work for users in fr/de/pt/zh/hi even before they ever visit English.
  return (
    currentDict[key] ||
    cache.get('en')?.[key] ||
    cache.get('es')?.[key] ||
    key
  )
}

/**
 * tf — interpolación simple sobre `t()`: reemplaza `{key}` por params[key].
 * Mantiene el placeholder `{name}` visible si una key no existe en el dict
 * activo, para que devs detecten keys faltantes rápido.
 */
export function tf(key: string, params: Record<string, string | number> = {}): string {
  const raw = t(key)
  if (!params || Object.keys(params).length === 0) return raw
  return raw.replace(/\{(\w+)\}/g, (_match, name) => {
    const v = params[name]
    return v == null ? `{${name}}` : String(v)
  })
}
